let current = 'it';

/**
 * Imposta la lingua.
 * @param {string} language `it`, `en` oppure `auto`
 * @param {string} [browserLanguage] lingua del browser, usata con `auto`
 * @returns {string} la lingua effettivamente in uso
 */
export function setLanguage(language, browserLanguage = (typeof navigator === 'undefined' ? 'it' : navigator.language)) {
  const wanted = language === 'auto' || language === undefined || language === null
    ? String(browserLanguage ?? 'it').slice(0, 2).toLowerCase()
    : String(language).toLowerCase();
  // Una lingua che non c'e' ricade sull'italiano, che e' quella completa.
  current = LANGUAGES.includes(wanted) ? wanted : 'it';
  return current;
}

/** Lingua in uso. */
export const language = () => current;

/**
 * Testo localizzato.
 * @param {string} key chiave del dizionario
 * @param {Record<string, string|number>} [values] valori da sostituire in `{nome}`
 * @returns {string}
 */
export function t(key, values) {
  const text = DICTIONARIES[current]?.[key] ?? DICTIONARIES.it[key] ?? key;
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in values ? String(values[name]) : match));
}

